import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { Readable } from 'node:stream';
import { readFile } from 'node:fs/promises';
import { buildChunkManifest } from '../scripts/generate-iso-chunk-manifest.mjs';
const bytes = Buffer.from('abcdefghijklmnopq');
const artifact = { size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
const generated = await buildChunkManifest(Readable.from([bytes.subarray(0, 3), bytes.subarray(3, 11), bytes.subarray(11)]), artifact, 8);
assert.equal(generated.schemaVersion, 1);
assert.equal(generated.artifactSize, bytes.length);
assert.equal(generated.chunks.length, 3);
assert.deepEqual(generated.chunks.map((chunk) => [chunk.index, chunk.start, chunk.end]), [[0, 0, 7], [1, 8, 15], [2, 16, 16]]);
for (const chunk of generated.chunks) assert.equal(chunk.sha256, createHash('sha256').update(bytes.subarray(chunk.start, chunk.end + 1)).digest('hex'));
await assert.rejects(() => buildChunkManifest(Readable.from([bytes]), { ...artifact, sha256: '0'.repeat(64) }, 8), /SHA-256 mismatch/);
await assert.rejects(() => buildChunkManifest(Readable.from([bytes.subarray(0, 3)]), artifact, 8), /size mismatch/);
const checkedIn = JSON.parse(await readFile('artifacts/developer-alpine-chunks.json', 'utf8'));
assert.equal(checkedIn.sourceStatus, 'template-not-deployable');
assert.ok(checkedIn.chunks.every(chunk => !/^[a-f0-9]{64}$/.test(chunk.sha256)), 'checked-in placeholder must not masquerade as verified chunk hashes');
const worker = await readFile('cloudflare/iso-worker.ts', 'utf8');
const workflow = await readFile('.github/workflows/deploy-cloudflare.yml', 'utf8');
assert.match(worker, /developerChunkManifestReady/);
assert.match(worker, /X-LinuxLab-Chunk-SHA256/);
assert.match(workflow, /node scripts\/generate-iso-chunk-manifest\.mjs/);
assert.match(workflow, /actions: read/, 'production deploy must be able to inspect CI runs');
assert.match(workflow, /actions\/workflows\/ci\.yml\/runs\?head_sha=/, 'production deploy must query CI for the exact tested commit');
assert.match(workflow, /run\.conclusion === "success"/, 'production deploy must require a successful CI conclusion');
assert.match(workflow, /run\.event === "push"/, 'manual workflow dispatch alone must not count as a passing CI run');

console.log('Developer Alpine chunk-manifest generation and verification contract passed');
